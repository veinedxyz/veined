import assets from "../routing/generated-assets.json" with { type: "json" };
import { networkIdentity } from "./networks";
// V1.5 CSP: network identity colours are applied through same-origin, build-time CSS classes
// (src/app/network-themes.css), never through inline style attributes. A theme maps to a class only
// when its exact validated colour tuple belongs to the reviewed source set; anything else (unknown,
// cloned with changes, injected) falls back to the neutral class. No runtime value reaches CSS text.
export interface ThemeColors {
  primary: string;
  accent: string;
  glow: string;
  badgeDark: string;
  badgeLight: string;
  logoSurface: string;
}
export const NEUTRAL_COLORS: ThemeColors = {
  primary: "#90938d",
  accent: "#b7baaf",
  glow: "144 147 141",
  badgeDark: "#d0d1cc",
  badgeLight: "#43453f",
  logoSurface: "transparent",
};
const HEX = /^#[0-9a-fA-F]{6}$/;
const RGB = /^(\d{1,3}) (\d{1,3}) (\d{1,3})$/;
export function validColors(t: ThemeColors): boolean {
  const rgb = RGB.exec(t.glow);
  return (
    HEX.test(t.primary) &&
    HEX.test(t.accent) &&
    HEX.test(t.badgeDark) &&
    HEX.test(t.badgeLight) &&
    (t.logoSurface === "transparent" || HEX.test(t.logoSurface)) &&
    !!rgb &&
    rgb.slice(1).every((v) => Number(v) <= 255)
  );
}
const tuple = (t: ThemeColors) =>
  [t.primary, t.accent, t.glow, t.badgeDark, t.badgeLight, t.logoSurface]
    .join("|")
    .toLowerCase();
// Reviewed sources in a fixed order: neutral, the two curated V1 identities, then catalog assets.
export const THEME_SOURCES: readonly { cls: string; colors: ThemeColors }[] =
  (() => {
    const out: { cls: string; colors: ThemeColors }[] = [
      { cls: "nt-neutral", colors: NEUTRAL_COLORS },
      { cls: "nt-onechain", colors: networkIdentity.onechain },
      { cls: "nt-bsc", colors: networkIdentity.bsc },
    ];
    const ids = Object.keys(assets as Record<string, ThemeColors>).sort(
      (a, b) =>
        a.length !== b.length ? a.length - b.length : a.localeCompare(b),
    );
    for (const id of ids)
      if (/^\d{1,20}$/.test(id))
        out.push({
          cls: `nt-c${id}`,
          colors: (assets as Record<string, ThemeColors>)[id],
        });
    return out.filter((s) => validColors(s.colors));
  })();
const byTuple = new Map<string, string>();
for (const s of THEME_SOURCES)
  if (!byTuple.has(tuple(s.colors))) byTuple.set(tuple(s.colors), s.cls);
export function themeClass(theme: ThemeColors | null | undefined): string {
  if (!theme) return "nt-neutral";
  return byTuple.get(tuple(theme)) ?? "nt-neutral";
}
export const networkThemeClass = (id: keyof typeof networkIdentity) =>
  themeClass(networkIdentity[id]);
// Background scene: source/destination glow classes on <main>.
export const sceneClasses = (
  source: ThemeColors | null | undefined,
  destination: ThemeColors | null | undefined,
) => `src-${themeClass(source)} dst-${themeClass(destination)}`;
// Deterministic stylesheet text for the committed src/app/network-themes.css (sync-tested).
export function themeStylesheet(): string {
  const seen = new Set<string>();
  const lines = [
    "/* Generated by scripts/network-themes-css.mjs from the reviewed network theme sources.",
    "   Do not edit by hand: tests/unit/v15-csp.test.ts verifies this file is in sync. */",
  ];
  for (const s of THEME_SOURCES) {
    if (seen.has(s.cls)) continue;
    seen.add(s.cls);
    const c = s.colors;
    lines.push(
      `.${s.cls}{--network-primary:${c.primary};--network-accent:${c.accent};--network-glow:${c.glow};--network-badge-dark:${c.badgeDark};--network-badge-light:${c.badgeLight};--network-logo-surface:${c.logoSurface}}`,
      `.src-${s.cls}{--source-glow:${c.glow}}`,
      `.dst-${s.cls}{--destination-glow:${c.glow}}`,
    );
  }
  return `${lines.join("\n")}\n`;
}
