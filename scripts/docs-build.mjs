// V1.11: compiles content/docs/<locale>/<slug>.md into src/docs/content.generated.ts (server-only data module, so
// the docs need no filesystem access at runtime). `--check` exits 1 when the generated module is out of date.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
const LOCALES = ["en", "tr"];
const pages = [
  ...readFileSync("src/docs/pages.ts", "utf8").matchAll(/^  "([a-z/-]+)",$/gm),
].map((m) => m[1]);
const docs = {};
for (const slug of pages) {
  docs[slug] = {};
  for (const locale of LOCALES) {
    const file = `content/docs/${locale}/${slug}.md`;
    if (!existsSync(file)) throw new Error(`MISSING_DOC ${file}`);
    const text = readFileSync(file, "utf8").replace(/\r\n/g, "\n");
    if (/<\s*(script|iframe|object|embed|style|img|svg)\b/i.test(text))
      throw new Error(`RAW_HTML_IN_DOC ${file}`);
    docs[slug][locale] = text;
  }
}
const out = `// GENERATED by scripts/docs-build.mjs from content/docs — do not edit.\nexport const DOCS: Record<string, Record<"en" | "tr", string>> = ${JSON.stringify(docs, null, 1)};\n`;
const target = "src/docs/content.generated.ts";
if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (current !== out) {
    console.error(
      "docs: src/docs/content.generated.ts is out of date (run pnpm docs:build)",
    );
    process.exit(1);
  }
  console.log("docs: generated module up to date");
} else {
  writeFileSync(target, out);
  console.log(`docs: ${pages.length} pages × ${LOCALES.length} locales`);
}
